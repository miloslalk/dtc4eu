#!/usr/bin/env python3
"""Generate V7__seed_dtcro_item_bank.sql from tools/dtcro_item_bank.csv.

The CSV is the client's authoritative DTCRO item bank (spec v0.2 register §2):
216 rows, columns form,area,area_name,letter,coordinate,item_text. Item texts
are clinical content and are emitted VERBATIM (including the client's typos) —
never edit them here. Re-run after replacing the CSV; the output is
deterministic so the migration diff shows exactly what changed.

Usage: python3 tools/generate_v7_item_bank.py
Writes: backend/src/main/resources/db/migration/V7__seed_dtcro_item_bank.sql
"""

import csv
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
CSV_PATH = REPO / "tools" / "dtcro_item_bank.csv"
OUT_PATH = REPO / "backend" / "src" / "main" / "resources" / "db" / "migration" / "V7__seed_dtcro_item_bank.sql"

# Canonical area names (register §2.1) — stored on questionnaire_areas.
CANONICAL_AREAS = {
    1: "Renewing hope and commitment",
    2: "Being supported by others",
    3: "Finding one's place in the local community",
    4: "Redefining oneself",
    5: "Assimilating the illness",
    6: "Managing symptoms",
    7: "Taking control",
    8: "Fighting stigma",
    9: "Developing empowerment",
}

# (form_code, administration_mode, stakeholder_category, display name, sort, expected item count)
FORMS = [
    ("USER",       "INDIVIDUAL", "USER",    "DTCRO — User Form",       1, 36),
    ("FAMILY",     "INDIVIDUAL", "FAMILY",  "DTCRO — Family Form",     2, 36),
    ("STAFF",      "INDIVIDUAL", "STAFF",   "DTCRO — Staff Form",      3, 45),
    ("MANAGER",    "INDIVIDUAL", "MANAGER", "DTCRO — Manager Form",    4, 27),
    ("LONG_FORM",  "LONG_FORM",  None,      "DTCRO — Long Form (community self-assessment)", 5, 45),
    ("DELEGATION", "DELEGATION", None,      "DTCRO — Delegation Form", 6, 27),
]
FORM_ORDER = {f[0]: f[4] for f in FORMS}


def esc(text: str) -> str:
    return text.replace("'", "''")


def main() -> None:
    rows = []
    with open(CSV_PATH, newline="", encoding="utf-8") as fh:
        for row in csv.DictReader(fh):
            rows.append({
                "form": row["form"].strip(),
                "area": int(row["area"]),
                "area_name": row["area_name"].strip(),
                "letter": row["letter"].strip(),
                "text": row["item_text"].strip(),
            })

    # --- validation ---------------------------------------------------------
    errors = []
    if len(rows) != 216:
        errors.append(f"expected 216 rows, got {len(rows)}")
    counts = {}
    for r in rows:
        if r["form"] not in FORM_ORDER:
            errors.append(f"unknown form {r['form']!r}")
        if not 1 <= r["area"] <= 9:
            errors.append(f"area out of range: {r}")
        if r["letter"] not in "abcde":
            errors.append(f"bad letter: {r}")
        counts[r["form"]] = counts.get(r["form"], 0) + 1
    for code, _, _, _, _, expected in FORMS:
        if counts.get(code, 0) != expected:
            errors.append(f"form {code}: expected {expected} items, got {counts.get(code, 0)}")
    # one area_name per (form, area)
    labels = {}
    for r in rows:
        key = (r["form"], r["area"])
        if key in labels and labels[key] != r["area_name"]:
            errors.append(f"conflicting area_name for {key}: {labels[key]!r} vs {r['area_name']!r}")
        labels[key] = r["area_name"]
    # register §2.2: DELEGATION wording equals LONG_FORM for letters a–c
    lf = {(r["area"], r["letter"]): r["text"] for r in rows if r["form"] == "LONG_FORM"}
    for r in rows:
        if r["form"] == "DELEGATION" and lf.get((r["area"], r["letter"])) != r["text"]:
            errors.append(f"DELEGATION {r['area']}.{r['letter']} differs from LONG_FORM")
    if errors:
        sys.exit("CSV validation failed:\n  " + "\n  ".join(errors))

    rows.sort(key=lambda r: (FORM_ORDER[r["form"]], r["area"], r["letter"]))

    # --- SQL ----------------------------------------------------------------
    out = []
    out.append("""-- ============================================================================
-- V7: seed the DTCRO six-form item bank (spec v0.2 register §2; source
-- tools/dtcro_item_bank.csv, 216 items). GENERATED by
-- tools/generate_v7_item_bank.py — do not edit by hand; regenerate instead.
--
-- !! DESTRUCTIVE (pre-production only) !!
-- The V4 DTCRO content was an explicitly-labelled PLACEHOLDER. This migration
-- deletes that definition AND any dev responses referencing it before seeding
-- the real content. Item texts are the client's VERBATIM clinical wording,
-- including their typos — never "fix" them in SQL.
-- ============================================================================

-- 1. Wipe the placeholder DTCRO definition and dependent dev data.
DELETE FROM questionnaire_responses
 WHERE questionnaire_id = (SELECT id FROM questionnaires WHERE code = 'DTCRO');
DELETE FROM facility_scale_scores
 WHERE questionnaire_id = (SELECT id FROM questionnaires WHERE code = 'DTCRO');
DELETE FROM questionnaire_items
 WHERE questionnaire_id = (SELECT id FROM questionnaires WHERE code = 'DTCRO');
DELETE FROM questionnaire_forms
 WHERE questionnaire_id = (SELECT id FROM questionnaires WHERE code = 'DTCRO');
DELETE FROM questionnaire_areas
 WHERE questionnaire_id = (SELECT id FROM questionnaires WHERE code = 'DTCRO');

-- 2. Areas R1–R9 (canonical names, register §2.1).
INSERT INTO questionnaire_areas (questionnaire_id, area_code, name, sort_order)
SELECT q.id, 'R' || v.n, v.name, v.n
FROM questionnaires q,
     (VALUES""")
    area_vals = ",\n".join(
        f"        ({n}, '{esc(name)}')" for n, name in CANONICAL_AREAS.items()
    )
    out.append(area_vals)
    out.append("""     ) AS v(n, name)
WHERE q.code = 'DTCRO';

-- 3. The six forms (register §2.2).
INSERT INTO questionnaire_forms (questionnaire_id, administration_mode, stakeholder_category, name, form_code, sort_order)
SELECT q.id, v.mode, v.category, v.name, v.form_code, v.sort_order
FROM questionnaires q,
     (VALUES""")
    form_vals = ",\n".join(
        "        ('{}', {}, '{}', '{}', {})".format(
            mode,
            f"'{cat}'" if cat else "NULL",
            esc(name),
            code,
            sort,
        )
        for code, mode, cat, name, sort, _ in FORMS
    )
    out.append(form_vals)
    out.append("""     ) AS v(mode, category, name, form_code, sort_order)
WHERE q.code = 'DTCRO';

-- 4. 216 items. item_code = {FORM}-{area}.{letter}; the coordinate
--    (area sort_order, item_letter) is the cross-form aggregation key.
INSERT INTO questionnaire_items
    (questionnaire_id, area_id, form_id, item_code, item_text, response_type, sort_order, item_letter)
SELECT q.id,
       a.id,
       f.id,
       v.form_code || '-' || v.area_no || '.' || v.letter,
       v.item_text,
       'LIKERT',
       v.area_no * 10 + (ascii(v.letter) - 96),
       v.letter
FROM (VALUES""")
    item_vals = ",\n".join(
        f"        ('{r['form']}', {r['area']}, '{r['letter']}', '{esc(r['text'])}')"
        for r in rows
    )
    out.append(item_vals)
    out.append("""     ) AS v(form_code, area_no, letter, item_text)
JOIN questionnaires q        ON q.code = 'DTCRO'
JOIN questionnaire_areas a   ON a.questionnaire_id = q.id AND a.area_code = 'R' || v.area_no
JOIN questionnaire_forms f   ON f.questionnaire_id = q.id AND f.form_code = v.form_code;

-- 5. Per-form area header phrasing, verbatim from the CSV (open question 12.5).
INSERT INTO questionnaire_form_area_labels (form_id, area_id, display_name)
SELECT f.id, a.id, v.display_name
FROM (VALUES""")
    label_rows = sorted(labels.items(), key=lambda kv: (FORM_ORDER[kv[0][0]], kv[0][1]))
    label_vals = ",\n".join(
        f"        ('{form}', {area}, '{esc(name)}')"
        for (form, area), name in label_rows
    )
    out.append(label_vals)
    out.append("""     ) AS v(form_code, area_no, display_name)
JOIN questionnaires q        ON q.code = 'DTCRO'
JOIN questionnaire_forms f   ON f.questionnaire_id = q.id AND f.form_code = v.form_code
JOIN questionnaire_areas a   ON a.questionnaire_id = q.id AND a.area_code = 'R' || v.area_no;

-- 6. The questionnaire is no longer a placeholder.
UPDATE questionnaires
   SET name = 'DTCRO Questionnaire (2nd Ed. EN)'
 WHERE code = 'DTCRO';
""")

    OUT_PATH.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUT_PATH} ({len(rows)} items, {len(label_rows)} area labels)")


if __name__ == "__main__":
    main()
